const BY_ID = new Map(QUESTS.map((q) => [q.id, q]));

export function quest(id: string): Quest {
  const q = BY_ID.get(id);
  if (!q) throw new Error(`Неизвестное задание: ${id}`);
  return q;
}

export function questsByTheme(theme: QuestTheme): Quest[] {
  return QUESTS.filter((q) => q.theme === theme);
}

