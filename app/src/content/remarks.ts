/**
 * Питомец реагирует на то, как ребёнок распределяет деньги прямо сейчас.
 * Состояние плана определяется по простым правилам (budgetMood), реплика
 * зависит от характера, подсказка – от состояния плана.
 */
export type BudgetMood = 'start' | 'needsLow' | 'wantsHeavy' | 'noSavings' | 'good';

/** Доля бюджета на обязательное, ниже которой питомцу грозит остаться голодным. */
export const NEEDS_SHARE_MIN = 0.3;

export function budgetMood(
  plan: { needs: number; wants: number; savings: number },
  income: number
): BudgetMood {
  const total = plan.needs + plan.wants + plan.savings;
  if (total === 0) return 'start';
  if (plan.needs < income * NEEDS_SHARE_MIN) return 'needsLow';
  if (plan.wants > plan.needs) return 'wantsHeavy';
  if (plan.savings === 0) return 'noSavings';
  return 'good';
}

