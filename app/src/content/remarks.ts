/**
 * В лавке питомец смотрит на ситуацию недели: есть ли план, куплено ли
 * обязательное, остались ли по плану деньги на желаемое.
 */
export type ShopMood = 'lowBalance' | 'noPlan' | 'needsFirst' | 'wantsOver' | 'ok';

export function shopMood(input: {
  balance: number;
  /** Самая дешёвая позиция каталога: если не хватает даже на неё – финкоинов мало. */
  cheapestPrice: number;
  planConfirmed: boolean;
  boughtNeeds: boolean;
  /** Сколько по плану осталось на желаемое (null – плана нет). */
  wantsLeft: number | null;
}): ShopMood {
  if (input.balance < input.cheapestPrice) return 'lowBalance';
  if (!input.planConfirmed) return 'noPlan';
  if (!input.boughtNeeds) return 'needsFirst';
  if (input.wantsLeft !== null && input.wantsLeft <= 0) return 'wantsOver';
  return 'ok';
}

