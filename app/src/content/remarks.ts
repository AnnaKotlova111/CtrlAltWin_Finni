/** В копилке питомец смотрит, есть ли цели и насколько они близко. */
export type SavingsMood = 'noGoal' | 'empty' | 'progress' | 'almost' | 'reached';

/** С какой доли накопленного цель считается «почти достигнутой». */
export const ALMOST_SHARE = 0.6;

/**
 * Настроение копилки по всем активным целям: радуемся, если хоть одна
 * накоплена или почти накоплена; «пусто» – только если нигде ничего нет.
 */
export function savingsMood(goals: { price: number; saved: number }[]): SavingsMood {
  if (goals.length === 0) return 'noGoal';
  if (goals.some((g) => g.saved >= g.price)) return 'reached';
  if (goals.every((g) => g.saved <= 0)) return 'empty';
  if (goals.some((g) => g.saved >= g.price * ALMOST_SHARE)) return 'almost';
  return 'progress';
}

