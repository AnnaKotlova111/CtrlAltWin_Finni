const BY_ID = new Map(SPECIES.map((s) => [s.id, s]));

export function species(id: SpeciesId): PetSpecies {
  const s = BY_ID.get(id);
  if (!s) throw new Error(`Неизвестный вид питомца: ${id}`);
  return s;
}

export function colorOption(id: SpeciesId, color: ColorId): PetColorOption {
  const s = species(id);
  return s.colors.find((c) => c.id === color) ?? s.colors[0];
}

/** Путь к спрайту питомца: готовые WebP лежат в public/assets/pets. */
export function petSprite(id: SpeciesId, color: ColorId, stage: Stage): string {
  return `./assets/pets/${id}-${color}-${stage}.webp`;
}

/**
 * Выбирает реплику по событию. Индекс детерминированный (по seed),
 * чтобы один и тот же экран не «дёргался» при перерисовке.
 */
export function petSays(id: SpeciesId, event: PetEvent, seed = 0): string {
  const bank = species(id).phrases[event];
  return bank[Math.abs(seed) % bank.length];
}

/** Общее число визуально различимых комбинаций «вид + окрас». */
export const APPEARANCE_COMBINATIONS = SPECIES.reduce((n, s) => n + s.colors.length, 0);
