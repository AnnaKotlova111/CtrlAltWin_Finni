/**
 * Каталог питомцев: внешний вид, характер и реплики.
 *
 * Характер каждого питомца связан с игровой механикой: на одно и то же
 * событие (отложил, купил лишнее, не хватило денег) разные питомцы
 * отвечают по-разному, в своей манере. Тексты взяты из описания характеров
 * и продолжены в том же духе.
 *
 * Важно: ни одна реплика не стыдит ребёнка и не пугает за питомца.
 */

import type { ColorId, SpeciesId, Stage } from '../engine/types';

/** События, на которые питомец реагирует репликой. */
export type PetEvent =
  /** Приветствие на главном экране. */
  | 'greet'
  /** Ребёнок пополнил копилку. */
  | 'save'
  /** Цель накопления достигнута. */
  | 'goalReached'
  /** Куплено необязательное. */
  | 'buyWant'
  /** Куплено обязательное. */
  | 'buyNeed'
  /** Не хватило финкоинов на покупку. */
  | 'noMoney'
  /** Период закрыт, факт сошёлся с планом. */
  | 'planOk'
  /** Период закрыт, потрачено сильно мимо плана. */
  | 'planOff'
  /** Обязательные расходы остались непокрытыми. */
  | 'needsMissing'
  /** Задание пройдено удачно. */
  | 'questGood'
  /** В задании было неудачное решение. */
  | 'questWeak'
  /** Новая стадия развития. */
  | 'stageUp';

export type PhraseBank = Record<PetEvent, string[]>;

export interface PetColorOption {
  id: ColorId;
  /** Подпись для экрана выбора. */
  label: string;
  /** Акцент питомца. Используется точечно: рамки, бейджи, подсветка.
   *  Основной UI остаётся cream + purple + gold. */
  accent: string;
}

export interface PetSpecies {
  id: SpeciesId;
  name: string;
  /** Короткое описание при выборе. */
  tagline: string;
  /** Чему питомец учит ребёнка – для раздела взрослого. */
  focus: string;
  /** Философия питомца. */
  philosophy: string;
  /** Названия стадий развития. */
  stageNames: [string, string, string];
  colors: PetColorOption[];
  phrases: PhraseBank;
}

